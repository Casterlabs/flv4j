package co.casterlabs.flv4j.test.util;

import java.io.FileInputStream;
import java.io.FileOutputStream;
import java.io.InputStream;
import java.io.OutputStream;

import co.casterlabs.flv4j.codecs.video.hvc1.HEVCDecoderConfigurationRecord;
import co.casterlabs.flv4j.codecs.video.hvc1.HEVCExVideoData;
import co.casterlabs.flv4j.codecs.video.hvc1.HEVCNalus;
import co.casterlabs.flv4j.codecs.video.hvc1.HEVCPacketType;
import co.casterlabs.flv4j.codecs.video.hvc1.HEVCVideoData;
import co.casterlabs.flv4j.flv.FLVFileHeader;
import co.casterlabs.flv4j.flv.muxing.NonSeekableFLVDemuxer;
import co.casterlabs.flv4j.flv.muxing.StreamFLVMuxer;
import co.casterlabs.flv4j.flv.tags.FLVTag;
import co.casterlabs.flv4j.flv.tags.FLVTagType;
import co.casterlabs.flv4j.flv.tags.script.FLVScriptTagData;
import co.casterlabs.flv4j.flv.tags.video.FLVStandardVideoTagData;
import co.casterlabs.flv4j.flv.tags.video.FLVVideoCodec;
import co.casterlabs.flv4j.flv.tags.video.FLVVideoFrameType;
import co.casterlabs.flv4j.flv.tags.video.ex.FLVExVideoTagData;
import co.casterlabs.flv4j.flv.tags.video.ex.FLVExVideoTrack;
import lombok.SneakyThrows;

// The non-standard "codec 12" HEVC format used in the wild (no authoritative spec).
// It is a standard FLV file with video codec id 12, using AVC-shaped packet framing:
//
//   [frameType:4][codecId:4 = 12]
//   [packetType:1]                0 = sequence header, 1 = NALU
//   [compositionTimeOffset:24]
//   [payload]                     sequence header = hvcC record, NALU = 4-byte length-prefixed NALUs
//
// This fixture tool converts an enhanced (eFLV) HEVC file (what current ffmpeg writes by
// default) into that format, so we can keep a codec 12 fixture in the tree without needing
// a legacy encoder. It walks the input with the library's own demuxer and re-muxes the
// video tags into their standard form. Usage:
//
//   java ConvertExHevcToCodec12 <enhanced-in.flv> <codec12-out.flv>
//
//Generated by: Qwen3.8-27b
public class ConvertExHevcToCodec12 {

    @SneakyThrows
    public static void main(String[] args) {
        try (InputStream in = new FileInputStream(args[0]);
            OutputStream out = new FileOutputStream(args[1])) {

            StreamFLVMuxer muxer = new StreamFLVMuxer(new FLVFileHeader(1, 0x01, new byte[0]), out);

            new NonSeekableFLVDemuxer() {
                @Override
                protected void onHeader(FLVFileHeader header) {
                    if (!header.isVideo()) {
                        throw new IllegalArgumentException("Input must be a video stream.");
                    }
                }

                @SneakyThrows
                @Override
                protected void onTag(long previousTagSize, FLVTag tag) {
                    if (tag.data() instanceof FLVScriptTagData script) {
                        // Pass the script tag (onMetaData) through as-is.
                        muxer.write(new FLVTag(FLVTagType.SCRIPT, tag.timestamp(), tag.streamId(), script));
                    } else if (tag.data() instanceof FLVExVideoTagData ex && ex.tracks().length == 1) {
                        FLVExVideoTrack track = ex.tracks()[0];
                        if (track.data() instanceof HEVCExVideoData h) {
                            HEVCVideoData data = switch (h.rawType()) {
                                // Sequence header: the hvcC record is the payload.
                                case /*SEQUENCE_START*/ 0 -> h.packetData() instanceof HEVCDecoderConfigurationRecord cfg ? HEVCVideoData.from(HEVCPacketType.SEQUENCE_HEADER, 0, cfg) : null;

                                // Coded frames: 3-byte CTO + 4-byte length-prefixed NALUs.
                                case /*CODED_FRAMES*/ 1 -> HEVCVideoData.from(HEVCPacketType.NALU, h.compositionTimeOffset(), new HEVCNalus(h.view().slice(3)));

                                // Coded frames, composition time offset implicitly zero.
                                case /*CODED_FRAMES_X*/ 3 -> HEVCVideoData.from(HEVCPacketType.NALU, 0, new HEVCNalus(h.view()));

                                // METADATA, SEQUENCE_END, etc. have no standard equivalent.
                                default -> null;
                            };

                            if (data != null) {
                                muxer.write(videoTag(tag, ex, data));
                            }
                        }
                    }
                }

                @Override
                protected void onEnd() {}
            }.start(in);
        }
    }

    private static FLVTag videoTag(FLVTag tag, FLVExVideoTagData ex, HEVCVideoData data) {
        return new FLVTag(
            FLVTagType.VIDEO,
            tag.timestamp(),
            tag.streamId(),
            FLVStandardVideoTagData.from(
                FLVVideoFrameType.LUT[ex.rawFrameType()],
                FLVVideoCodec.NS_HEVC,
                data
            )
        );
    }

}
