package co.casterlabs.flv4j.test.util;

import java.io.ByteArrayOutputStream;
import java.io.FileInputStream;
import java.io.FileOutputStream;
import java.io.InputStream;
import java.io.OutputStream;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;

import co.casterlabs.flv4j.actionscript.io.ASWriter;
import lombok.SneakyThrows;

// Converts a VP8 WebM (ffmpeg libvpx, single video track) into a veovera enhanced
// FLV (FourCC "vp08") fixture. ffmpeg cannot write VP8 to FLV, and libvpx writes
// no CodecPrivate element into the WebM, so:
//   - the sequence header's VPCodecConfigurationRecord (12B "vpcc") is synthesized
//     (profile 0, level 1, 8-bit, 4:2:0, limited range, BT.709 colour triple),
//   - the SimpleBlock payloads are passed through as raw coded frames.
//
// Output layout (see FLVFileHeader / FLVExVideoTagData):
//   FLV header (9B, flags 0x01 = video) + prevTagSize0 (4B)
//   video tag  ts=0:          0x90 "vp08" [VPCodecConfigurationRecord]
//   video tag  ts=i*1000/24:  0x91 (key) / 0xA1 (inter) "vp08" [raw frame]
//   4B prevTagSize trailers after each tag, final prevTagSize 0
//
// The WebM SimpleBlock timestamps are relative to their cluster and are
// re-sequenced to the source's 24fps grid here.
//
// Usage:
//   java ConvertVp8WebmToFlv <in.webm> <out.flv>
//
//Generated by: Qwen3.8-27b
public class ConvertVp8WebmToFlv {

    static final int EBML_SEGMENT = 0x18538067;
    static final int EBML_TRACK = 0x1654AE6B;
    static final int EBML_CLUSTER = 0x1F43B675;
    static final int EBML_SIMPLE_BLOCK = 0xA3;

    // Synthesized VPCodecConfigurationRecord: version 1, profile 0, level 1,
    // 8-bit, 4:2:0, limited range, colourPrimaries/transfer/matrix = 2 (BT.709),
    // no initialisation data. Matches the source WebM's ffprobe stream info.
    static final byte[] VPCC = {
            0x01,
            0x00,
            0x00,
            0x00,
            0x00,
            0x01,
            (byte) 0x80,
            0x02,
            0x02,
            0x02,
            0x00,
            0x00
    };

    static final byte[] FOURCC = "vp08".getBytes();

    @SneakyThrows
    public static void main(String[] args) {
        byte[] webm;
        try (InputStream in = new FileInputStream(args[0])) {
            webm = in.readAllBytes();
        }

        List<byte[]> frames = new ArrayList<>();
        List<Boolean> keyframes = new ArrayList<>();
        parseTopLevel(webm, frames, keyframes);

        if (frames.isEmpty()) {
            throw new IllegalStateException("No SimpleBlocks found in " + args[0]);
        }

        byte[] flv = buildFlv(frames, keyframes);

        try (OutputStream out = new FileOutputStream(args[1])) {
            out.write(flv);
        }

        int keys = 0;
        for (boolean key : keyframes) {
            keys += key ? 1 : 0;
        }
        System.out.println("frames=" + frames.size() + " keyframes=" + keys + " flv_size=" + flv.length);
    }

    @SneakyThrows
    private static byte[] buildFlv(List<byte[]> frames, List<Boolean> keyframes) {
        ByteArrayOutputStream baos = new ByteArrayOutputStream();
        ASWriter writer = new ASWriter(baos);

        // FLV header. NB: flags 0x01 = video (this codebase's convention,
        // matching FFmpeg's FLV_HEADER_FLAG_HASVIDEO).
        writer.bytes("FLV".getBytes());
        writer.u8(1); // version
        writer.u8(0x01); // flags
        writer.u32(9); // header size

        writer.u32(0); // previous tag size 0

        // Sequence header: ex | KEY_FRAME | SEQUENCE_START.
        writer.u8(9);
        writer.u24(1 + 4 + VPCC.length);
        writer.u24(0); // timestamp
        writer.u8(0); // timestamp extended
        writer.u24(0); // stream id
        writer.u8(1 << 7 | 1 << 4 | 0);
        writer.bytes(FOURCC);
        writer.bytes(VPCC);
        writer.u32(11 + 1 + 4 + VPCC.length); // previous tag size

        // Coded frames: ex | frameType | CODED_FRAMES + FourCC + raw frame.
        for (int i = 0; i < frames.size(); i++) {
            int frameType = keyframes.get(i) ? 1 /*KEY_FRAME*/ : 2 /*INTER_FRAME*/;
            int timestamp = (int) (i * 1000L / 24);

            writer.u8(9);
            writer.u24(1 + 4 + frames.get(i).length);
            writer.u24(timestamp & 0xFFFFFF);
            writer.u8((timestamp >>> 24) & 0xFF);
            writer.u24(0); // stream id
            writer.u8(1 << 7 | frameType << 4 | 1);
            writer.bytes(FOURCC);
            writer.bytes(frames.get(i));
            writer.u32(11 + 1 + 4 + frames.get(i).length); // previous tag size
        }

        writer.u32(0); // final previous tag size
        return baos.toByteArray();
    }

    // ----------------- EBML (byte-sanity only, no codec parsing) -----------------

    private static void parseTopLevel(byte[] data, List<byte[]> frames, List<Boolean> keyframes) {
        int pos = 0;
        while (pos < data.length) {
            int id = readId(data, pos);
            int sizePos = pos + vintLength(data, pos);
            long size = readVintValue(data, sizePos);
            int bodyStart = sizePos + vintLength(data, sizePos);

            if (id == EBML_SEGMENT) {
                pos = parseSegment(data, bodyStart, (int) size, frames, keyframes);
            } else {
                pos = bodyStart + (int) size; // EBML header, etc.
            }
        }
    }

    private static int parseSegment(byte[] data, int start, int size, List<byte[]> frames, List<Boolean> keyframes) {
        int end = start + size;
        int pos = start;
        while (pos < end) {
            int id = readId(data, pos);
            int sizePos = pos + vintLength(data, pos);
            long elementSize = readVintValue(data, sizePos);
            int bodyStart = sizePos + vintLength(data, sizePos);

            if (id == EBML_CLUSTER) {
                pos = parseCluster(data, bodyStart, (int) elementSize, frames, keyframes);
            } else {
                pos = bodyStart + (int) elementSize; // Track, SeekHead, Info, Cues, ...
            }
        }
        return pos;
    }

    private static int parseCluster(byte[] data, int start, int size, List<byte[]> frames, List<Boolean> keyframes) {
        int end = start + size;
        int pos = start;
        while (pos < end) {
            int id = readId(data, pos);
            int sizePos = pos + vintLength(data, pos);
            long elementSize = readVintValue(data, sizePos);
            int bodyStart = sizePos + vintLength(data, sizePos);

            if (id == EBML_SIMPLE_BLOCK) {
                int bodyEnd = bodyStart + (int) elementSize;

                // TrackNumber: unsigned vint.
                int trackNumber = (int) readVintValue(data, bodyStart);
                int posIn = bodyStart + vintLength(data, bodyStart);

                // Timestamp: relative to the cluster, in milliseconds.
                // FFmpeg writes this as a fixed 2-byte big-endian value
                // (avio_wb16 in matroskaenc.c, EBML_BLOCK case), not a
                // variable-width vint, despite the Matroska spec's "signed
                // vint" description. It is ignored here; the frames are
                // re-sequenced onto the source's 24fps grid in buildFlv.
                int relTs = (data[posIn] << 8) | data[posIn + 1];
                if (data[posIn] < 0) {
                    throw new IllegalStateException("Negative SimpleBlock timestamp: " + relTs);
                }
                int flagsPos = posIn + 2;

                int flags = data[flagsPos] & 0xFF;
                int payloadStart = flagsPos + 1;

                if (trackNumber == 1) {
                    frames.add(Arrays.copyOfRange(data, payloadStart, bodyEnd));
                    keyframes.add((flags & 0x80) != 0);
                }

                pos = bodyEnd;
            } else {
                pos = bodyStart + (int) elementSize; // Cluster Timestamp, Unknown, ...
            }
        }
        return pos;
    }

    private static int vintLength(byte[] data, int pos) {
        int b = data[pos] & 0xFF;
        int length = 1;
        int mask = 0x80;
        while (length <= 8 && (b & mask) == 0) {
            length++;
            mask >>= 1;
        }
        if (length > 8) {
            throw new IllegalArgumentException("VINT too long at " + pos);
        }
        return length;
    }

    // Element IDs keep their leading marker bit (FFmpeg's MKEBML constants do).
    private static int readId(byte[] data, int pos) {
        int length = vintLength(data, pos);
        int val = 0;
        for (int i = 0; i < length; i++) {
            val = (val << 8) | (data[pos + i] & 0xFF);
        }
        return val;
    }

    // Value VINTs: the leading marker bit is a length marker, not part of the
    // value.
    private static long readVintValue(byte[] data, int pos) {
        int length = vintLength(data, pos);
        int val = data[pos] & (0xFF >> length);
        for (int i = 1; i < length; i++) {
            val = (val << 8) | (data[pos + i] & 0xFF);
        }
        return val;
    }

}
